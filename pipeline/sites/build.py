"""Build config/sites.yaml from human-approved OSM ids.

APPROVED lists the OSM way/relation ids a human reviewed against imagery
(see docs/ASSUMPTIONS.md). The polygon, area and centroid come from OSM.
Usage: python -m pipeline.sites.build
"""
from __future__ import annotations

import json

import yaml
from shapely.geometry import mapping, shape

from pipeline.common.config import CACHE_DIR, CONFIG_DIR
from pipeline.common.geo import to_metric, utm_epsg

# site_id, display name, city, osm id, demo flag
APPROVED = [
    ("ghazipur", "Ghazipur", "delhi", "way/76727509", True),
    ("bhalswa", "Bhalswa", "delhi", "way/414943488", True),
    ("okhla", "Okhla", "delhi", "way/608169272", True),
    # OSM maps only the 6.5 ha plant (way/1262085027); the waste surface was traced from Sentinel-2 (config/traced/).
    ("brahmapuram", "Brahmapuram", "kochi", "traced", False),
    ("deonar", "Deonar", "mumbai", "way/289511744", False),
    ("kanjur", "Kanjur", "mumbai", "way/257455760", False),
    # Added 2026-10-11: sites with documented recurring fires (see data/news_fires.csv).
    ("perungudi", "Perungudi", "chennai", "way/84106307", False),  # OSM name "Pallikaranai Dumpyard"
    ("kodungaiyur", "Kodungaiyur", "chennai", "way/29199633", False),
    ("dhapa", "Dhapa", "kolkata", "way/325363390", False),
    # Pirana (Ahmedabad, way/321136517) left out: from 2023 a persistent heat source on the site (FIRMS type=2,
    # plus co-located unflagged detections) dominates the record, so fire days there are not fire events. See docs/ASSUMPTIONS.md.
]

CITY_NAMES = {"delhi": "Delhi", "kochi": "Kochi", "mumbai": "Mumbai", "gurugram": "Gurugram", "bengaluru": "Bengaluru", "hyderabad": "Hyderabad", "chennai": "Chennai", "kolkata": "Kolkata", "ahmedabad": "Ahmedabad"}


def load_candidates(city: str) -> dict[str, dict]:
    p = CACHE_DIR / "osm" / f"candidates_{city}.geojson"
    fc = json.loads(p.read_text())
    return {f["properties"]["osm"]: f for f in fc["features"]}


def build(approved=APPROVED) -> list[dict]:
    cache: dict[str, dict] = {}
    sites = []
    for site_id, name, city, osm, demo in approved:
        search_city = "delhi" if city == "gurugram" else city
        if search_city not in cache:
            cache[search_city] = load_candidates(search_city)
        if osm == "traced":
            f = json.loads((CONFIG_DIR / "traced" / f"{site_id}.geojson").read_text())
        else:
            f = cache[search_city][osm]
        poly = shape(f["geometry"]).simplify(0.00001, preserve_topology=True)
        c = poly.centroid
        epsg = utm_epsg(c.x, c.y)
        m = to_metric(poly, epsg)
        sites.append(
            {
                "site_id": site_id,
                "name": name,
                "city": city,
                "city_name": CITY_NAMES[city],
                "osm_id": osm if osm != "traced" else "traced:" + f["properties"]["traced_from"],
                "boundary_source": "osm" if osm != "traced" else "traced",
                "approved": True,
                "demo": demo,
                "utm_epsg": epsg,
                "area_ha": round(m.area / 1e4, 1),
                "centroid": [round(c.x, 5), round(c.y, 5)],
                "polygon": json.loads(json.dumps(mapping(poly))),
            }
        )
    return sites


def main() -> None:
    sites = build()
    with open(CONFIG_DIR / "sites.yaml", "w", encoding="utf-8") as f:
        f.write("# Generated by pipeline.sites.build from human-approved OSM polygons. (c) OpenStreetMap contributors, ODbL.\n")
        yaml.safe_dump({"sites": sites}, f, sort_keys=False, allow_unicode=True, default_flow_style=None, width=200)
    for s in sites:
        print(s["site_id"], s["area_ha"], "ha", s["centroid"], "EPSG", s["utm_epsg"])


if __name__ == "__main__":
    main()
